def display_prompts():
    """
    카테고리와 프롬프트를 표시합니다.
    """
    # 데이터 준비
    categories = prepare_data()

    # 사이드바 설정
    st.sidebar.title("목차")

    # 카테고리별 메뉴
    for category, prompts in categories.items():
        st.sidebar.subheader(category)
        for prompt in prompts:
            title = prompt['title']
            # 링크의 앵커를 고유하게 만들기 위해 카테고리도 포함
            anchor = f"{category.replace(' ', '-')}-{title.replace(' ', '-')}"
            st.sidebar.markdown(f"- [{title}](#{anchor})")

    # 메인 콘텐츠
    st.title("실습 프롬프트")
    st.markdown("---")

    # 카테고리별 프롬프트 표시
    for category, prompts in categories.items():
        st.header(category)
        for prompt in prompts:
            title = prompt['title']
            content = prompt['content']

            # 고유한 앵커 생성
            anchor = f"{category.replace(' ', '-')}-{title.replace(' ', '-')}"

            # 제목 라인을 제외한 나머지 내용 추출
            content_lines = content.split('\n')
            actual_content = '\n'.join(content_lines[1:]).strip()

            # 앵커 포인트 추가
            st.markdown(f"<a name='{anchor}'></a>", unsafe_allow_html=True)
            st.subheader(title)
            st.markdown("```\n" + actual_content + "\n```")
            st.markdown("---")

